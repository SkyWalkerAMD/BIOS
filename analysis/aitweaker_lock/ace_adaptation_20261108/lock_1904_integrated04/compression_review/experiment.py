HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent
LAB = PROJECT / "lab"
ROOT = next(p for p in HERE.parents if (p / "tools/pydeps").is_dir())
DRIVER = PROJECT / "driver/build/AiTweakerLock1904.efi"
EXPECTED_DRIVER = "463b94139cb64207e1b756965ebb9ca3513250c8712bbbcd20798fd317dec904"
sys.path.insert(0, str(LAB))
import build_asus_review as builder


def sha(data):
    return hashlib.sha256(data).hexdigest()


def write_json(path, data):
    path.write_text(json.dumps(data, indent=2), encoding="utf8")


def prepare():
    assert sha(DRIVER.read_bytes()) == EXPECTED_DRIVER
    captured = {}
    original_compress = lzma.compress

    class Captured(Exception):
        pass

    def capture(data, format, filters):
        assert format == lzma.FORMAT_ALONE and filters == [builder.FILTER]
        captured.update(data=bytes(data), filters=filters)
        raise Captured()

    # Execute the exact builder's entire pre-compression path and assertions.
    # Only redirect its output allowance in memory; no original file is edited.
    builder.OUT = HERE
    try:
        lzma.compress = capture
        try:
            builder.build(DRIVER, HERE / "capture_only.review.bin")
        except Captured:
            pass
    finally:
        lzma.compress = original_compress
    assert captured
    raw = captured["data"]
    source = builder.SOURCE.read_bytes()
    section_length = int.from_bytes(source[builder.SECTION:builder.SECTION+3], "little")
    original = lzma.decompress(source[builder.SECTION+24:builder.SECTION+section_length], format=lzma.FORMAT_ALONE)
    free, available, files = builder.find_free(original, builder.INNER)
    _, _, outer_files = builder.find_free(source, builder.OUTER)
    allocation = int.from_bytes(source[builder.CONTAINER+20:builder.CONTAINER+23], "little")
    ffs = builder.ffs_for_driver(DRIVER.read_bytes(), builder.GUID, "AiTweaker Lock W790 ACE 1904")
    assert raw[free:free+len(ffs)] == ffs
    for item in files:
        offset = int(item["offset"], 16)
        assert sha(raw[offset:offset+item["size"]]) == item["sha256"]
    (HERE / "modified_inner.bin").write_bytes(raw)
    shutil.copy2(LAB / "build_asus_review.py", HERE / "builder.snapshot.py")
    report = {"status": "EXACT_BUILDER_INPUT_CAPTURED", "driver_sha256": EXPECTED_DRIVER,
              "driver_bytes": DRIVER.stat().st_size, "builder_sha256": sha((LAB / "build_asus_review.py").read_bytes()),
              "source_sha256": sha(source), "source": str(builder.SOURCE),
              "modified_inner_sha256": sha(raw), "modified_inner_bytes": len(raw),
              "original_inner_sha256": sha(original), "original_inner_bytes": len(original),
              "inner_tail_growth": len(raw)-len(original), "inserted_ffs_offset": hex(free),
              "inserted_ffs_bytes": len(ffs), "original_inner_free_bytes": available,
              "original_inner_files": files, "original_outer_files": outer_files,
              "outer_container_offset": hex(builder.CONTAINER), "outer_container_allocation": allocation,
              "maximum_packed_bytes_with_24_byte_padding_ffs": allocation-24-48,
              "base_filter": builder.FILTER,
              "scope": "Exact pre-compression input generated by the current builder; all original FFS bytes and offsets checked; no image was flashed."}
    write_json(HERE / "input.json", report)
    print(json.dumps({k: report[k] for k in ["status", "modified_inner_sha256", "modified_inner_bytes", "inner_tail_growth", "outer_container_allocation", "maximum_packed_bytes_with_24_byte_padding_ffs"]}, indent=2))


def compress(args):
    meta = json.loads((HERE / "input.json").read_text(encoding="utf8"))
    raw = (HERE / "modified_inner.bin").read_bytes()
    assert sha(raw) == meta["modified_inner_sha256"]
    assert sha(DRIVER.read_bytes()) == EXPECTED_DRIVER
    params = dict(meta["base_filter"])
    params.update(depth=args.depth, lc=args.lc, lp=args.lp, pb=args.pb, dict_size=args.dict_mib * 1024 * 1024)
    tag = f"d{args.dict_mib}_lc{args.lc}_lp{args.lp}_pb{args.pb}_depth{args.depth}"
    folder = HERE / tag
    assert not folder.exists(), "Preserve previous attempts; use different parameters"
    folder.mkdir()
    start = time.perf_counter()
    cpu_start = time.process_time()
    packed = lzma.compress(raw, format=lzma.FORMAT_ALONE, filters=[params])
    seconds = time.perf_counter() - start
    cpu_seconds = time.process_time() - cpu_start
    packed = packed[:5] + len(raw).to_bytes(8, "little") + packed[13:]
    decode_start = time.perf_counter()
    decoded = lzma.decompress(packed[13:], format=lzma.FORMAT_RAW, filters=[params])
    decode_seconds = time.perf_counter() - decode_start
    assert decoded == raw
    needed = builder.align(48 + len(packed), 8)
    padding = meta["outer_container_allocation"] - needed
    (folder / "stream.lzma").write_bytes(packed)
    report = {"status": "COMPRESSION_ROUNDTRIP_PASS", "tag": tag, "filter": params,
              "compressed_bytes": len(packed), "compressed_sha256": sha(packed),
              "lzma_properties_header_hex": packed[:13].hex(), "compression_seconds": round(seconds, 3),
              "process_cpu_seconds": round(cpu_seconds, 3), "raw_decode_seconds": round(decode_seconds, 3),
              "decoded_sha256": sha(decoded), "decoded_exact_match": True,
              "container_required_aligned_bytes": needed, "padding_ffs_bytes": padding,
              "fits_original_allocation_with_padding": padding >= 24,
              "spare_bytes_after_minimum_padding": padding - 24,
              "driver_sha256": EXPECTED_DRIVER, "input_sha256": meta["modified_inner_sha256"],
              "timing_note": "Wall-clock and process CPU measurements on the shared review workstation; concurrent tasks may affect elapsed time."}
    write_json(folder / "result.json", report)
    print(json.dumps(report, indent=2), flush=True)


def collect(root):
    entries = []
    for path in root.rglob("info.txt"):
        info = path.read_text(encoding="utf8", errors="replace")
        if not re.search(r"^Type: File\s*$", info, re.M):
            continue
        guid = re.search(r"^File GUID: (\S+)", info, re.M)
        if not guid:
            continue
        header = (path.parent / "header.bin").read_bytes()
        body_path = path.parent / "body.bin"
        body = body_path.read_bytes() if body_path.exists() else b""
        if not body_path.exists():
            size = re.search(r"^Full size: ([0-9A-Fa-f]+)h", info, re.M)
            assert size and int(size[1], 16) == len(header)
        entries.append({"guid": guid[1].upper(), "sha256": sha(header + body), "folder": path.parent, "info": info})
    return entries


def verify(tag):
    folder = HERE / tag
    result = json.loads((folder / "result.json").read_text(encoding="utf8"))
    meta = json.loads((HERE / "input.json").read_text(encoding="utf8"))
    assert result["fits_original_allocation_with_padding"]
    source = builder.SOURCE.read_bytes()
    assert sha(source) == builder.SOURCE_SHA == meta["source_sha256"]
    assert sha(DRIVER.read_bytes()) == EXPECTED_DRIVER
    raw = (HERE / "modified_inner.bin").read_bytes()
    packed = (folder / "stream.lzma").read_bytes()
    assert sha(packed) == result["compressed_sha256"]
    assert lzma.decompress(packed[13:], format=lzma.FORMAT_RAW, filters=[result["filter"]]) == raw
    section = bytearray(source[builder.SECTION:builder.SECTION+24])
    section[:3] = (24 + len(packed)).to_bytes(3, "little")
    body = bytes(section) + packed
    replacement = builder.ffs_header(source[builder.CONTAINER:builder.CONTAINER+24], body) + body
    needed = builder.align(len(replacement), 8)
    padding = meta["outer_container_allocation"] - needed
    assert padding >= 24
    replacement += b"\xff" * (needed - len(replacement)) + builder.padding_file(padding)
    end = builder.CONTAINER + meta["outer_container_allocation"]
    candidate = source[:builder.CONTAINER] + replacement + source[end:]
    assert len(candidate) == len(source) and candidate[:builder.CONTAINER] == source[:builder.CONTAINER] and candidate[end:] == source[end:]
    assert candidate[:4096] == source[:4096]
    builder.valid_fv(candidate, builder.OUTER)
    builder.validate_ffs(candidate, builder.CONTAINER, len(body) + 24)
    builder.validate_ffs(candidate, builder.CONTAINER + needed, padding)
    for entry in meta["original_inner_files"]:
        offset = int(entry["offset"], 16)
        assert sha(raw[offset:offset+entry["size"]]) == entry["sha256"]
    for entry in meta["original_outer_files"]:
        offset = int(entry["offset"], 16)
        if offset != builder.CONTAINER:
            assert sha(candidate[offset:offset+entry["size"]]) == entry["sha256"]
    path = folder / "W790-ACE-1904-compression.review.bin"
    assert not path.exists()
    path.write_bytes(candidate)
    command = [str(ROOT / "tools/UEFIExtract_A75/UEFIExtract.exe"), str(path), "all"]
    start = time.perf_counter()
    completed = subprocess.run(command, capture_output=True)
    elapsed = time.perf_counter() - start
    (folder / "extract.stdout.txt").write_bytes(completed.stdout)
    (folder / "extract.stderr.txt").write_bytes(completed.stderr)
    assert completed.returncode == 0, completed.stderr[-2000:]
    original = collect(Path(str(builder.SOURCE) + ".dump"))
    extracted = collect(Path(str(path) + ".dump"))
    container_guid = "9E21FD93-9C72-4C15-8C4B-E77F1DB2D792"
    old = Counter((item["guid"], item["sha256"]) for item in original if item["guid"] != container_guid)
    new = Counter((item["guid"], item["sha256"]) for item in extracted if item["guid"] != container_guid)
    assert not old-new, old-new
    inserted = [item for item in extracted if item["guid"] == str(builder.GUID).upper()]
    assert len(inserted) == 1
    item = inserted[0]
    payload = next(item["folder"].glob("*PE32*/body.bin")).read_bytes()
    assert payload == DRIVER.read_bytes()
    assert "invalid" not in item["info"].lower()
    depex = next(item["folder"].glob("*dependency*/body.bin")).read_bytes()
    assert len(depex) == 36 and depex[-2:] == b"\x03\x08"
    old_report = Path(str(builder.SOURCE) + ".report.txt").read_text(encoding="utf8")
    new_report = Path(str(path) + ".report.txt").read_text(encoding="utf8")
    unknown = lambda text: Counter(tuple(s.strip() for s in line.split("|")[0:2] + line.split("|")[4:5]) for line in text.splitlines() if "| Unknown" in line)
    assert unknown(old_report) == unknown(new_report)
    verification = {"status": "PASS_FITS_FIXED_SLOT_AND_INDEPENDENT_UEFIEXTRACT", "tag": tag,
                    "candidate": str(path), "candidate_sha256": sha(candidate), "driver_sha256": EXPECTED_DRIVER,
                    "source_sha256": meta["source_sha256"], "compression": result,
                    "uefiextract_command": command, "uefiextract_exit_code": completed.returncode,
                    "uefiextract_seconds": round(elapsed, 3), "original_inner_ffs_bytes_and_offsets_preserved": len(meta["original_inner_files"]),
                    "original_outer_other_ffs_bytes_and_offsets_preserved": len(meta["original_outer_files"]) - 1,
                    "independently_extracted_original_ffs_preserved_except_container": sum(old.values()),
                    "original_ffs_total": len(original), "candidate_ffs_total": len(extracted),
                    "inserted_driver_payload_exact_match": True, "unknown_section_inventory_unchanged": True,
                    "all_bytes_outside_original_container_preserved": True, "capsule_length_preserved": True,
                    "original_capsule_header_preserved": True, "original_signature_authenticates_modified_payload": False,
                    "decoded_input_exact_match": True, "hardware_or_flashing_performed": False}
    write_json(folder / "verification.json", verification)
    print(json.dumps(verification, indent=2), flush=True)


def main():
    parser = argparse.ArgumentParser()
    subs = parser.add_subparsers(dest="mode", required=True)
    subs.add_parser("prepare")
    compressor = subs.add_parser("compress")
    compressor.add_argument("--depth", type=int, required=True)
    compressor.add_argument("--dict-mib", type=int, default=16)
    compressor.add_argument("--lc", type=int, default=3)
    compressor.add_argument("--lp", type=int, default=0)
    compressor.add_argument("--pb", type=int, default=2)
    validator = subs.add_parser("verify")
    validator.add_argument("--tag", required=True)
    args = parser.parse_args()
    if args.mode == "prepare":
        prepare()
    elif args.mode == "compress":
        compress(args)
    else:
        assert args.tag.replace("_", "").isalnum()
        verify(args.tag)


if __name__ == "__main__":
    main()
